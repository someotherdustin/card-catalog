test("a user-defined type: no status, fields and links as pairs, an index outside its directory", () => {
  const root = makeRepo(postmortems);
  const { built } = reindex(root, "docs/postmortems");
  assert.equal(
    read(root, "docs/postmortems.md"),
    [
      "# Postmortem index",
      "",
      "Generated by the card-catalog plugin from the postmortems in `postmortems`. Edits here are overwritten.",
      "One line per postmortem: `label amended key=value … | title | summary`. Search it with grep, then open the postmortems that match.",
      "",
      "- [Postmortem 2026-09-14-db-outage](postmortems/2026-09-14-db-outage.md) 2026-09-01 severity=high follows=ADR-0001 | DB \\| outage | The primary failed \\| over.",
      '- [Postmortem 2026-09-20-dns](postmortems/2026-09-20-dns.md) 2026-09-01 follows="Postmortem 2026-09-14-db-outage" | DNS | Resolver timeouts.',
      "",
    ].join("\n"),
  );
  assert.match(read(root, "docs/postmortems/index.json"), /"type":"postmortem"/);
  assert.deepEqual(built.skipped, [{ file: "notes.md", reason: "not-a-record", message: "name doesn't match id pattern {date}-{slug}" }]);
  assert.deepEqual(
    built.records.map((r) => r.links),
    [[{ type: "follows", target: "ADR-0001", file: "../adr/0001-a.md" }], [{ type: "follows", target: "Postmortem 2026-09-14-db-outage", file: "2026-09-14-db-outage.md" }]],
  );
});

test("links resolve in their own collection first, then across the repo", () => {
  const root = makeRepo({
    "docs/adr/0001-a.md": adr("A", "Body.", "relates-to: [ADR-0002, ADR-0009, Some free text]"),
    "docs/adr/0002-b.md": adr("B"),
    "svc/one/docs/adr/0009-x.md": adr("X"),
    "svc/two/docs/adr/0009-y.md": adr("Y"),
    "svc/one/docs/adr/0003-c.md": adr("C", "Body.", "supersedes: [ADR-0001](../../../../docs/adr/0001-a.md)\nrelates-to: [gone](0099-gone.md)"),
  });
  const own = build(root).built;
  assert.deepEqual(own.records[0]?.links, [
    { type: "relates-to", target: "ADR-0002", file: "0002-b.md" },
    { type: "relates-to", target: "ADR-0009" },
    { type: "relates-to", target: "Some free text" },
  ]);
  assert.deepEqual(own.problems.map((p) => p.code), ["ambiguous-link", "missing-index"]);
  const other = build(root, "svc/one/docs/adr").built;
  assert.deepEqual(other.records[0]?.links, [
    { type: "supersedes", target: "ADR-0001", file: "../../../../docs/adr/0001-a.md" },
    { type: "relates-to", target: "gone", file: "0099-gone.md" },
  ]);
  assert.deepEqual(other.problems.map((p) => p.code), ["broken-link", "missing-index"]);
});

test("ignored files and nested collections' files are not records", () => {
  const root = makeRepo({
    ".aiignore": "docs/notes/private-*.md\n",
    "docs/notes/a.md": adr("A"),
    "docs/notes/private-b.md": adr("B"),
    "docs/notes/sub/c.md": adr("C"),
    "docs/notes/adr-dir/docs/adr/0001-x.md": adr("X"),
    "card-catalog.json": { collections: [{ dir: "docs/notes", type: "note", match: "**/*.md" }, { dir: "docs/notes/sub", type: "other" }] },
  });
  assert.deepEqual(build(root, "docs/notes").built.records.map((r) => r.file), ["a.md"]);
});

test("git's ignore rules still apply to records reached through a symlinked directory", () => {
  const root = makeRepo({ ".gitignore": "0002-secret.md\n", "shared/adr/0001-a.md": adr("A"), "shared/adr/0002-secret.md": adr("Secret") }, { git: true });
  mkdirSync(join(root, "svc/docs"), { recursive: true });
  symlinkSync(join(root, "shared/adr"), join(root, "svc/docs/adr"));
  assert.deepEqual(build(root, "svc/docs/adr").built.records.map((r) => r.file), ["0001-a.md"]);
});
